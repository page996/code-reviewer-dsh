/**
 * lib/hooks.mjs — CONTRACT §7: git hooks install / uninstall / run.
 *
 * `installHooks({ cwd, log, root? })`   -> writes `.githooks/pre-commit` +
 *   `.githooks/pre-push` (POSIX sh) and sets `git config core.hooksPath .githooks`.
 * `uninstallHooks({ cwd, log })`        -> unsets `core.hooksPath` (files kept).
 * `runHook({ name, cwd, config, log })` -> executes one hook's checks.
 *
 * Hook modes (`hooks.preCommit` / `hooks.prePush`: off|fast|full, default fast):
 *   - off   : do nothing (exit 0);
 *   - fast  : deterministic only. pre-commit runs `gate.commands` only (no
 *             LLM, no autodetect) and fails on gate failure; pre-push computes
 *             the push range and runs the gate (configured commands +
 *             autodetect);
 *   - full  : delegates to the CLI (`review all`) as a child process, which
 *             performs scope -> plan -> LLM review -> gate -> report.
 *
 * `REVIEW_SKIP_HOOKS=1` always short-circuits with one log line and exit 0.
 *
 * The generated hooks are POSIX sh and call
 * `node "$ROOT/bin/review.mjs" hook <name>`; `$ROOT` is the tool checkout root
 * (overridable with the `root` option for tests).
 */

import { chmodSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync as nodeSpawnSync } from 'node:child_process';
import { runGate } from './gate.mjs';

const HOOK_NAMES = Object.freeze(['pre-commit', 'pre-push']);
const MODES = new Set(['off', 'fast', 'full']);
const DEFAULT_TOOL_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const EXIT_ENGINE_ERROR = 5;

function makeError(code, message) {
  const err = new Error(message);
  err.code = code;
  return err;
}

function asArray(value) {
  return Array.isArray(value) ? value : [];
}

function toText(value) {
  if (value === null || value === undefined) return '';
  return typeof value === 'string' ? value : String(value);
}

function makeLogger(log) {
  return (level, message, extra) => {
    if (typeof log !== 'function') return;
    try {
      log(level, message, extra);
    } catch {
      /* logging must never break a hook */
    }
  };
}

function toPosixPath(value) {
  return toText(value).replace(/\\/g, '/');
}

function shellQuoteDouble(value) {
  return toPosixPath(value)
    .replace(/\\/g, '\\\\')
    .replace(/"/g, '\\"')
    .replace(/\$/g, '\\$')
    .replace(/`/g, '\\`');
}

function git(args, cwd, env) {
  const result = nodeSpawnSync('git', args, {
    cwd,
    env: env ?? process.env,
    encoding: 'utf8',
    windowsHide: true,
  });
  return {
    status: typeof result.status === 'number' ? result.status : result.status ?? null,
    stdout: toText(result.stdout),
    stderr: toText(result.stderr),
    error: result.error,
  };
}

function isGitRepo(cwd) {
  if (!cwd || !existsSync(cwd)) return false;
  const result = git(['rev-parse', '--git-dir'], cwd);
  return result.status === 0;
}

