function stagedFiles(cwd, env) {
  const result = git(['diff', '--cached', '--name-only'], cwd, env);
  if (result.status !== 0) return [];
  return result.stdout
    .split(/\r?\n/)
    .map((line) => line.trim())
    .filter(Boolean);
}

function resolvePushBase(cwd, env) {
  const upstream = git(['rev-parse', '--abbrev-ref', '--symbolic-full-name', '@{upstream}'], cwd, env);
  if (upstream.status === 0) {
    const ref = upstream.stdout.trim();
    if (ref) return ref;
  }
  return 'main';
}

function rangeFiles(cwd, env, base) {
  const mergeBase = git(['merge-base', 'HEAD', base], cwd, env);
  const resolvedBase = mergeBase.status === 0 && mergeBase.stdout.trim() ? mergeBase.stdout.trim() : base;
  const diff = git(['diff', '--name-only', `${resolvedBase}..HEAD`], cwd, env);
  return {
    base,
    mergeBase: resolvedBase,
    files:
      diff.status === 0
        ? diff.stdout
            .split(/\r?\n/)
            .map((line) => line.trim())
            .filter(Boolean)
        : [],
  };
}

function emptyAggregate() {
  return {
    schemaVersion: 1,
    findings: [],
    counts: { blocker: 0, major: 0, minor: 0, needsHuman: 0, dropped: 0 },
    verdict: 'pass',
    blocking: [],
    humanAttention: [],
    errors: [],
  };
}

function hookMode(config, name) {
  const hooks = config?.hooks && typeof config.hooks === 'object' ? config.hooks : {};
  const enabled = hooks.enabled !== false;
  if (!enabled) return 'off';
  const raw = name === 'pre-commit' ? hooks.preCommit : hooks.prePush;
  const normalized = toText(raw ?? 'fast').trim().toLowerCase();
  return MODES.has(normalized) ? normalized : 'fast';
}

function findCliEntry(root) {
  const candidate = join(root, 'bin', 'review.mjs');
  return existsSync(candidate) ? candidate : null;
}

function spawnCliAll({ name, cwd, config, env, log, spawnSyncImpl, root }) {
  const cli = findCliEntry(root ?? DEFAULT_TOOL_ROOT);
  if (!cli) {
    throw makeError('CONFIG', '找不到 bin/review.mjs，无法执行 full 模式的 hook（请先完成 CLI 构建）');
  }
  const workDir = resolve(cwd);
  const args = [cli, 'all', '--repo', workDir];
  if (name === 'pre-commit') {
    args.push('--mode', 'staged');
  } else {
    const base = resolvePushBase(workDir, env);
    args.push('--mode', 'range', '--base', base);
  }
  if (config?.review?.effort) args.push('--effort', toText(config.review.effort));
  if (config?.review?.contractFile) args.push('--contract', toText(config.review.contractFile));
  log?.('info', `hook(full): ${process.execPath} ${args.slice(1).join(' ')}`);
  const result = (spawnSyncImpl ?? nodeSpawnSync)(process.execPath, args, {
    cwd: workDir,
    env,
    stdio: 'inherit',
    windowsHide: true,
  });
  const exitCode =
    typeof result.status === 'number'
      ? result.status
      : result.error
        ? EXIT_ENGINE_ERROR
        : EXIT_ENGINE_ERROR;
  return { exitCode, cli, args: args.slice(1) };
}

/**
 * Execute one git hook.
 *
 * @param {{name: 'pre-commit'|'pre-push', cwd?: string, config?: object,
 *          log?: Function, env?: object, root?: string, spawnSync?: Function}} args
 */
export async function runHook({ name, cwd, config, log, env, root, spawnSync } = {}) {
  const logger = makeLogger(log);
  if (!HOOK_NAMES.includes(name)) {
    throw makeError('USAGE', `未知的 hook: ${name}（可选 ${HOOK_NAMES.join('|')}）`);
  }
  const environment = env && typeof env === 'object' ? env : process.env;
  if (toText(environment.REVIEW_SKIP_HOOKS) === '1') {
    logger('info', 'REVIEW_SKIP_HOOKS=1，跳过 git hook 检查');
    return { name, skipped: true, reason: 'REVIEW_SKIP_HOOKS=1', exitCode: 0 };
  }

  const workDir = typeof cwd === 'string' && cwd.trim() !== '' ? resolve(cwd) : process.cwd();
  if (!isGitRepo(workDir)) {
    throw makeError('GIT', `不是 git 仓库，无法运行 hook: ${workDir}（请用 --repo 指定仓库）`);
  }
  const mode = hookMode(config, name);
  if (mode === 'off') {
    logger('info', `hook(${name}): hooks 配置为 off，跳过`);
    return { name, mode, skipped: true, reason: 'hooks-off', exitCode: 0 };
  }

  const scope =
    name === 'pre-commit'
      ? { mode: 'staged', files: stagedFiles(workDir, environment) }
      : (() => {
          const base = resolvePushBase(workDir, environment);
          return { mode: 'range', ...rangeFiles(workDir, environment, base) };
        })();
  logger(
    'info',
    `hook(${name}): mode=${mode} scope=${scope.mode} files=${asArray(scope.files).length}`,
  );

  if (mode === 'full') {
    const result = spawnCliAll({
      name,
      cwd: workDir,
      config,
      env: environment,
      log: logger,
      spawnSyncImpl: spawnSync,
      root,
    });
    return { name, mode, scope, skipped: false, exitCode: result.exitCode };
  }

  // fast mode: deterministic checks only, never LLM.
  const gateConfig = config?.gate && typeof config.gate === 'object' ? config.gate : {};
  const hookGateConfig =
    name === 'pre-commit'
      ? { ...config, gate: { ...gateConfig, commands: gateConfig.commands ?? [], autodetect: false } }
      : config;
  const gate = await runGate({
    cwd: workDir,
    config: hookGateConfig,
    aggregate: emptyAggregate(),
    log: logger,
  });
  const failed = asArray(gate.checks).filter(
    (check) => !check.skipped && check.required !== false && check.exit !== 0,
  );
  if (failed.length > 0) {
    logger('warn', `hook(${name}): ${failed.length} 个确定性门禁失败，阻止提交/推送`);
  }
  return {
    name,
    mode,
    scope,
    skipped: false,
    gate,
    exitCode: gate.exitCode,
  };
}

export const HOOKS = HOOK_NAMES;

export default { installHooks, uninstallHooks, runHook };
