/** Build the POSIX sh hook body exactly as required by the CONTRACT. */
export function buildHookScript(name, root) {
  if (!HOOK_NAMES.includes(name)) throw makeError('USAGE', `未知的 hook: ${name}`);
  const quotedRoot = shellQuoteDouble(root ?? DEFAULT_TOOL_ROOT);
  return [
    '#!/bin/sh',
    `# dsh-code-reviewer ${name} hook — generated by \`review install-hooks\``,
    'command -v node >/dev/null 2>&1 || exit 0',
    `ROOT="${quotedRoot}"`,
    `node "$ROOT/bin/review.mjs" hook ${name} || exit $?`,
    '',
  ].join('\n');
}

function writeHookFile(file, content) {
  writeFileSync(file, content, 'utf8');
  try {
    chmodSync(file, 0o755);
  } catch {
    /* chmod is a no-op / unsupported on some Windows setups; git still runs it */
  }
}

function repoTopLevel(cwd) {
  const result = git(['rev-parse', '--show-toplevel'], cwd);
  return result.status === 0 && result.stdout.trim() ? resolve(result.stdout.trim()) : resolve(cwd);
}

/**
 * @param {{cwd?: string, log?: Function, root?: string}} args
 */
export function installHooks({ cwd, log, root } = {}) {
  const logger = makeLogger(log);
  if (typeof cwd !== 'string' || cwd.trim() === '') {
    throw makeError('USAGE', 'installHooks 需要 cwd');
  }
  const workDir = resolve(cwd);
  if (!isGitRepo(workDir)) {
    throw makeError('GIT', `不是 git 仓库，无法安装 hooks: ${workDir}`);
  }
  // Hooks live at the repository top-level; installing from a subdirectory must
  // not create a stray `<subdir>/.githooks` that git never executes.
  const repoRoot = repoTopLevel(workDir);
  const toolRoot = typeof root === 'string' && root.trim() !== '' ? resolve(root) : DEFAULT_TOOL_ROOT;
  if (!existsSync(join(toolRoot, 'bin', 'review.mjs'))) {
    logger('warn', `installHooks: ${join(toolRoot, 'bin', 'review.mjs')} 尚不存在（CLI 未构建时 hook 会直接失败）`);
  }

  const hooksDir = join(repoRoot, '.githooks');
  mkdirSync(hooksDir, { recursive: true });
  const files = [];
  for (const name of HOOK_NAMES) {
    const file = join(hooksDir, name);
    if (existsSync(file)) {
      let existing = '';
      try {
        existing = readFileSync(file, 'utf8');
      } catch {
        existing = '';
      }
      if (!existing.includes('dsh-code-reviewer')) {
        logger('warn', `installHooks: 覆盖已存在的非本工具 hook: ${file}`);
      }
    }
    writeHookFile(file, buildHookScript(name, toolRoot));
    files.push(file);
  }

  const configResult = git(['config', 'core.hooksPath', '.githooks'], repoRoot);
  if (configResult.status !== 0) {
    throw makeError(
      'GIT',
      `设置 git config core.hooksPath 失败: ${configResult.stderr.trim() || configResult.error?.message || 'unknown'}`,
    );
  }
  logger('info', `installHooks: 已安装 ${files.length} 个 hook（core.hooksPath=.githooks）`);
  return {
    installed: true,
    hooksPath: '.githooks',
    directory: hooksDir,
    files,
    root: toolRoot,
  };
}

/**
 * Restore the previous hook setup: unset `core.hooksPath`; keep the generated
 * hook files on disk (CONTRACT).
 */
export function uninstallHooks({ cwd, log } = {}) {
  const logger = makeLogger(log);
  if (typeof cwd !== 'string' || cwd.trim() === '') {
    throw makeError('USAGE', 'uninstallHooks 需要 cwd');
  }
  const workDir = resolve(cwd);
  if (!isGitRepo(workDir)) {
    throw makeError('GIT', `不是 git 仓库，无法卸载 hooks: ${workDir}`);
  }
  const repoRoot = repoTopLevel(workDir);
  const current = git(['config', '--get', 'core.hooksPath'], repoRoot);
  const currentValue = current.status === 0 ? current.stdout.trim() : '';
  const hadHooksPath = currentValue !== '';
  // Only unset when the configured hooksPath belongs to this tool; otherwise we
  // would silently break Husky or another hook manager.
  const ours = hadHooksPath
    && (currentValue === '.githooks' || resolve(repoRoot, currentValue) === join(repoRoot, '.githooks'));
  let removed = false;
  if (hadHooksPath && !ours) {
    logger('warn', `uninstallHooks: core.hooksPath=${currentValue} 不是本工具设置，保留不动`);
  } else if (ours) {
    const unset = git(['config', '--unset', 'core.hooksPath'], repoRoot);
    removed = unset.status === 0;
    if (!removed && unset.status !== 5) {
      logger('warn', `uninstallHooks: 删除 core.hooksPath 失败: ${unset.stderr.trim()}`);
    }
  }
  const files = HOOK_NAMES.map((name) => join(repoRoot, '.githooks', name)).filter((file) =>
    existsSync(file),
  );
  logger('info', `uninstallHooks: core.hooksPath ${removed ? '已删除' : ours ? '无需删除' : '非本工具，已保留'}（hook 文件保留）`);
  return {
    uninstalled: !hadHooksPath || removed,
    removed,
    hooksPath: hadHooksPath && !ours ? currentValue : null,
    filesKept: files,
    preservedForeignHooksPath: hadHooksPath && !ours,
  };
}

